def test_session_exposes_cl_pool_and_liquidity_views(cl_pack: Pack):
    s = Session.create(session_id="s", pack=cl_pack, bankroll_raw=BANK, mask_seed="m", engine_seed="e")
    env = s.handle("r1", "markets.list", {"filters": {"execution_supported_only": True}})
    assert env.status == "ok", env.error
    items = {i["pool_id"]: i for i in env.data["items"]}
    pid1 = s.alias.pool(POOL1)
    assert set(items) == {pid1}  # POOL2 is not discoverable yet
    p = items[pid1]
    assert p["venue_model"] == "uniswap_v3_cl" and p["execution_supported"] is True
    assert p["fee_pips"] == FEE and p["tick_spacing"] == SPACING and "hooks" not in p
    env = s.handle("r2", "market.liquidity", {"pool_id": pid1})
    assert env.status == "ok", env.error
    d = env.data
    st = s.sim.pools[POOL1]
    assert d["model"] == "uniswap_v3_cl" and d["sqrt_price_x96"] == str(st.sqrt_price_x96) and d["tick"] == st.tick and d["liquidity"] == str(st.liquidity)
    x, y = st.virtual_reserves()
    assert d["virtual_depth"] == [{"asset_id": "NATIVE", "depth_raw": str(x)}, {"asset_id": s.alias.asset(TOKEN), "depth_raw": str(y)}]
    assert d["fee_pips"] == FEE and "active tick range" in d["note"]
    near = d["initialized_ticks_near_price"]
    assert [t["tick"] for t in near] == [-20000, -2000, 2000, 20000] and all(isinstance(t["liquidity_net"], str) for t in near)
    # quote, submit, advance and portfolio through the session
    env = s.handle("r3", "broker.quote", {"pool_id": pid1, "asset_in": "NATIVE", "amount_in_raw": str(10**17)})
    assert env.status == "ok", env.error
    assert env.data["fee"] == {"numerator": 1_000_000 - FEE, "denominator": 1_000_000, "note": "embedded in output; not charged again"}
    env = s.handle("r4", "broker.submit", {"pool_id": pid1, "asset_in": "NATIVE", "asset_out": s.alias.asset(TOKEN), "amount_in_raw": str(10**17), "min_amount_out_raw": "0", "deadline_ms": 10**7, "idempotency_key": "k"})
    assert env.status == "ok", env.error
    s.handle("r5", "clock.advance", {"to_ms": s.now + 10_000})
    env = s.handle("r6", "portfolio.get", {})
    holding = next(h for h in env.data["valuation"]["holdings"] if h["asset_id"] == s.alias.asset(TOKEN))
    assert holding["class"] == "priced_liquidatable" and holding["pool_id"] == pid1
    # the v4 pool with hooks: listed after its discovery, hook address aliased, never raw
    s.handle("r7", "clock.advance", {"to_ms": block_time(POOL2_BLOCK) - START_MS + DELAY_MS + 10_000})
    pid2 = s.alias.pool(POOL2)
    env = s.handle("r8", "markets.get", {"pool_id": pid2})
    assert env.status == "ok", env.error
    assert env.data["venue_model"] == "uniswap_v4_cl" and env.data["execution_supported"] is True
    assert env.data["hooks"].startswith("hook_") and HOOKS not in env.data["hooks"]
    env = s.handle("r9", "market.liquidity", {"pool_id": pid2})
    assert env.status == "ok" and env.data["liquidity"] == str(L1) and env.data["fee_pips"] == FEE2
