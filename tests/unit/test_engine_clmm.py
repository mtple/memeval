"""Concentrated-liquidity pools in the replay engine: validation, replay, quotes, fills, valuation, views.

The pack is built in-process with ``build_pack``. Its tape is generated by driving a ``ClPoolState``
with the same exact v3 math the engine uses, so every ``cl_swap`` row's after-values are
self-consistent and the no-agent replay must reconcile with zero mismatches.
"""

